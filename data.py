def get_rule_key(item_id):
    # 將項次轉換為清潔的字串比較
    clean_id = str(item_id).strip()
    for key in SPECIAL_RULES_MAP.keys():
        if "-" in key:
            try:
                start, end = map(int, key.split("-"))
                if start <= int(float(clean_id)) <= end: return key
            except: pass
        if clean_id == key: return key
    return None

