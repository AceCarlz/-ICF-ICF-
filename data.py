# 2. 升級版函數：它會自動判斷要抓大項還是細項
def add_range(start, end, name_prefix, eval_type, center_only, rules):
    for i in range(start, end + 1):
        idx = str(i)
        co = center_only(i) if callable(center_only) else center_only
        
        # 關鍵：如果在 SUB_NAMES 有定義就用細項，沒有就維持大項
        display_name = SUB_NAMES.get(idx, f"{name_prefix} (項次 {idx})")
        
        DEVICES[idx] = {
            "name": display_name,
            "eval": eval_type,
            "center_only": co,
            "rules": rules
        }

