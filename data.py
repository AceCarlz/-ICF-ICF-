# ==========================================
# 輔助函式
# ==========================================

def get_rule_key(item_id):
    clean_id = str(item_id).strip()
    # 支援 4.5.6 -> 4 這種主項次匹配
    main_num = clean_id.split('.')[0]
    try:
        val = int(main_num)
        for key in SPECIAL_RULES_MAP.keys():
            if "-" in key:
                s, e = map(int, key.split("-"))
                if s <= val <= e: return key
            elif key == main_num or key == clean_id:
                return key
    except: pass
    return None

